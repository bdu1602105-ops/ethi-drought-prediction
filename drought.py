def recommend_crops(risk, zone=None, top=5):
    """Crops most often recommended in the dataset for the same risk level and zone."""
    subset = df[(df["Drought_Risk"] == risk) & (df["Agro_Ecological_Zone"] == zone)]
    if len(subset) < 8:                       # too few records for this zone -> use all zones
        subset = df[df["Drought_Risk"] == risk]
    crops = subset["Recommended_Crops"].str.split(",").explode().str.strip()
    share = (crops.value_counts() / len(subset)).head(top)
    return [f"{crop} ({value:.0%})" for crop, value in share.items()]


