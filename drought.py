from sklearn.compose import ColumnTransformer
from sklearn.impute import SimpleImputer
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OneHotEncoder, StandardScaler


def make_preprocessor(numerical_cols, categorical_cols):
    """Numbers: fill gaps with the median and scale. Categories: fill gaps and one-hot encode."""
    steps = []
    if numerical_cols:
        steps.append(("num", Pipeline([("impute", SimpleImputer(strategy="median")),
                                       ("scale", StandardScaler())]), list(numerical_cols)))
    if categorical_cols:
        steps.append(("cat", Pipeline([("impute", SimpleImputer(strategy="most_frequent")),
                                       ("onehot", OneHotEncoder(handle_unknown="ignore", sparse_output=False))]),
                      list(categorical_cols)))
    return ColumnTransformer(steps, remainder="drop")


