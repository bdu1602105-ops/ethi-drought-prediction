def predict_scenario(rainfall, max_temp, min_temp, humidity, evapotranspiration, soil_moisture,
                     zone=None, model=best_estimator):
    row = pd.DataFrame([{"Rainfall_mm": rainfall, "Max_Temp_C": max_temp, "Min_Temp_C": min_temp,
                         "Humidity_pct": humidity, "Evapotranspiration_mm": evapotranspiration,
                         "Soil_Moisture_pct": soil_moisture, "Agro_Ecological_Zone": zone}])
    row = add_engineered_features(row)[FEATURE_COLUMNS]
    proba = model.predict_proba(row)
    return {"risk": CODE_TO_CLASS[int(proba.argmax())],
            "probabilities": {n: float(p) for n, p in zip(CLASS_NAMES, proba[0].round(3))},
            "risk_index": round(float(risk_index_from_probabilities(proba)[0]), 1)}


